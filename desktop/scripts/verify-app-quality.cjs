// Real Electron, synthetic local fixture. No model calls or user data.
const { app, BrowserWindow, session } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const http = require('node:http');
const { createAppQualityInspector } = require('../core/app-quality.cjs');
const root = path.resolve(process.argv[2]);
app.setPath('userData', path.join(root, 'profile'));
app.on('window-all-closed', () => {});
app.whenReady().then(async () => {
  let server, requests = 0;
  try {
    server = http.createServer((_req, res) => { requests++; res.end('forbidden'); });
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    const project = path.join(root, 'project');
    await fs.mkdir(path.join(project, 'public'), { recursive: true });
    const source = `<!doctype html><html lang="da"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{font:16px sans-serif;margin:24px}button{padding:16px} .wide{width:1100px}</style><h1>Prøve</h1><p>Kun syntetiske data</p><button onclick="missingRestaurant.name">Åbn menu</button><button onclick="window.open('https://example.com')">Nyt vindue</button><input><div class="wide">Layoutfejl</div><script>localStorage.setItem('quality-only','true');</script></html>`;
    await fs.writeFile(path.join(project, 'public/index.html'), source);
    const inspect = createAppQualityInspector({ BrowserWindow, session, directory: path.join(root, 'reports') });
    const result = await inspect({ root: project });
    await fs.writeFile(path.join(root, 'result.json'), JSON.stringify(result, null, 2));
    assert.equal(result.status, 'checked');
    assert(result.findings.some(f => f.id === 'runtime-error'));
    assert(result.findings.some(f => f.id === 'horizontal-overflow'));
    assert.equal(result.visualDesign, 'not-reviewed');
    assert.equal(requests, 0);
    assert.equal(BrowserWindow.getAllWindows().length, 0);
    assert.equal(await fs.readFile(path.join(project, 'public/index.html'), 'utf8'), source);
    assert.equal(result.views[0].width, 1440); assert.equal(result.views[1].width, 390);
    console.log('PASS native runtime error, responsive geometry, local snapshot, network denial, popup denial, no source writes');
    await fs.writeFile(path.join(project, 'public/index.html'), '<!doctype html><html lang="da"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{font:16px sans-serif}button{padding:16px}</style><h1>Normal brug</h1><button onclick="this.textContent=\'Valgt\'">Vælg</button></html>');
    const fixed = await inspect({ root: project });
    assert.equal(fixed.status, 'checked'); assert.equal(fixed.findings.filter(f => f.severity === 'error').length, 0);
    assert.notEqual(fixed.fingerprint, result.fingerprint);
    console.log('PASS repaired app rechecked without false runtime/overflow errors');
    await fs.writeFile(path.join(project, 'public/index.html'), `<h1>Network fixture</h1><img src="https://example.com/photo.jpg"><script>fetch('http://127.0.0.1:${server.address().port}/leak').catch(()=>{});</script>`);
    const offline = await inspect({ root: project });
    assert.equal(offline.status, 'unsupported'); assert.equal(requests, 0);
    assert.equal(offline.findings.some(f => f.id === 'broken-image'), false);
    console.log('PASS blocked remote dependencies do not trigger destructive design repairs');
    await fs.writeFile(path.join(project, 'public/index.html'), `<html lang="da"><meta charset="utf-8"><style>body{font:16px sans-serif;color:#222;background:white}button{padding:16px}</style><div class="loading">Indlæser</div><script>
      if(typeof RTCPeerConnection !== 'undefined' || typeof WebTransport !== 'undefined') throw Error('Network constructor available');
      if(localStorage.getItem('prior-visit')) throw Error('Storage not reset'); localStorage.setItem('prior-visit','yes');
      window.addEventListener('beforeunload', e => {e.preventDefault();e.returnValue='stay';});
      setTimeout(()=>{document.body.innerHTML='<h1>Færdig indlæst</h1><button onclick="alert(1)">Åbn dialog</button><p style="color:#eee">Lav kontrast</p><img loading="lazy" style="margin-top:3000px" src="late.png">';},600);
    </script></html>`);
    const delayed = await inspect({ root: project });
    assert.equal(delayed.status, 'checked'); assert.equal(delayed.views[0].headings, 1);
    assert.equal(delayed.views[0].loading, false); assert(delayed.findings.some(f=>f.id==='low-contrast'));
    assert.equal(delayed.findings.some(f=>f.id==='runtime-error'), false);
    assert.equal(delayed.findings.some(f=>f.id==='broken-image'), false);
    assert.equal(requests,0); assert.equal(BrowserWindow.getAllWindows().length,0);
    console.log('PASS delayed rendering, contrast, lazy images, denied dialogs, storage reset and disabled network constructors');
    await fs.writeFile(path.join(project, 'public/index.html'), '<style>body{margin:0;font:16px sans-serif}.banner{position:fixed;inset:0 0 auto;height:60px;background:#444;z-index:10}.card{cursor:pointer;padding:24px;border:1px solid}</style><div class="banner">Fast header</div><main><h1>Skjult overskrift</h1><div class="card">Vælg sted</div></main><script>document.querySelector(".card").addEventListener("click",()=>document.querySelector("main").style.display="none");</script>');
    const navigation = await inspect({root:project});
    assert.equal(navigation.status,'checked');
    assert(navigation.findings.some(f=>f.id==='covered-heading'));
    assert(navigation.findings.some(f=>f.id==='empty-main-after-click' && f.severity==='warning'));
    assert(navigation.findings.some(f=>f.id==='nonsemantic-control'));
    assert.equal(navigation.clicks,1);
    console.log('PASS custom card click, main visibility review warning and header covering a title');
    await fs.writeFile(path.join(project, 'public/index.html'), '<!doctype html><html lang="da"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{margin:24px;background:#fff;color:#fff;font:16px sans-serif}.backed{position:relative;isolation:isolate;padding:24px}.backed::before{content:"";position:absolute;inset:0;background:#111;z-index:-1}.plain{color:#eee}</style><section class="backed"><h1>Læsbart på mørk dekoration</h1><p>Hvid tekst over sort pseudoelement</p></section><p class="plain">Reelt for lav kontrast</p></html>');
    const composited = await inspect({root:project});
    assert.equal(composited.status,'checked');
    assert.equal(composited.views[0].lowContrast,1,'only the genuinely low-contrast plain text is counted');
    assert.equal(composited.views[1].lowContrast,1);
    console.log('PASS painted pseudo-background is uncertain; genuine plain contrast fault remains detected');
    const controller = new AbortController(); controller.abort();
    assert.equal((await inspect({ root: project, signal: controller.signal })).status, 'cancelled');
    assert.equal(BrowserWindow.getAllWindows().length, 0);
    console.log('PASS Stop closes the isolated inspector');
    await fs.writeFile(path.join(root, 'verification.json'), JSON.stringify({ passed: true, scenarios: ['runtime-and-layout','repaired-snapshot','remote-dependencies','delayed-render-and-browser-boundaries','custom-card-navigation','painted-pseudo-contrast','stop'], requests, original: result, fixed, delayed, navigation, composited }, null, 2));
    server.close(); app.exit(0);
  } catch (error) { console.error(error); server?.close(); app.exit(1); }
});
